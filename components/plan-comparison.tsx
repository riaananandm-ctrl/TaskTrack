'use client';

import { Button } from '@/components/ui/button';
import { Card } from '@/components/ui/card';
import { Check, X, Sparkles, Crown, Loader2 } from 'lucide-react';
import { cn } from '@/lib/utils';
import {
  getEntitlements,
  getProfileEntitlements,
  planPriceLine,
  type PlanId,
} from '@/lib/entitlements';
import type { PaidPlanId } from '@/lib/premium-contact';
import { useAuth } from '@/lib/auth-context';

const FREE_FEATURES: { label: string; included: boolean }[] = [
  { label: 'TaskTrack AI — 40 credits a month', included: true },
  { label: 'Basic task and reminder management', included: true },
  { label: 'Basic planner and calendar', included: true },
  { label: 'Quizzes with 5 questions', included: true },
  { label: 'Basic flashcards (5 cards)', included: true },
  { label: 'Whiteboard (no AI tutor)', included: true },
  { label: 'Whiteboard AI tutor', included: false },
  { label: 'AI Detector', included: false },
  { label: 'Rewrite Coach', included: false },
];

const PRO_FEATURES: { label: string; included: boolean }[] = [
  { label: 'TaskTrack AI — 500 credits a month', included: true },
  { label: 'Unlimited tasks and reminders', included: true },
  { label: 'Quizzes with 5–8 questions, flashcards with 8–12', included: true },
  { label: 'Worked examples and personalized study plans', included: true },
  { label: 'Study slides generated by TaskTrack AI', included: true },
  { label: 'Whiteboard AI tutor that sees and draws on your board', included: true },
  { label: 'AI Detector (15 checks a day)', included: true },
  { label: 'Advanced progress and weak-topic insights', included: true },
  { label: 'Rewrite Coach', included: false },
];

const MAX_FEATURES: { label: string; included: boolean }[] = [
  { label: 'TaskTrack AI — 1,000 credits a month', included: true },
  { label: 'Everything in Premium', included: true },
  { label: 'Rewrite Coach: edit suggestions for your own drafts (50 a day)', included: true },
  { label: 'AI Detector (30 checks a day)', included: true },
  { label: 'Whiteboard AI tutor', included: true },
];

interface PlanComparisonProps {
  /** Called when the student picks a paid plan (opens the UPI checkout). */
  onUpgrade?: (plan: PaidPlanId) => void;
  upgrading?: boolean;
  upgradeNotice?: string | null;
}

/** Free vs Premium vs Max, with a "Current plan" label on the active plan. */
export function PlanComparison({ onUpgrade, upgrading, upgradeNotice }: PlanComparisonProps) {
  const { profile } = useAuth();
  const active = getProfileEntitlements(profile).id;
  const free = getEntitlements('free');
  const pro = getEntitlements('pro');
  const max = getEntitlements('max');

  return (
    <div className="space-y-4">
      <p className="text-xs text-muted-foreground text-center">
        Credits are used by size: a short chat costs 1, a long chat or a big document costs a few more.
      </p>
      {/* Three columns on large screens, stacked on mobile so every price stays readable. */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        <PlanCard
          planId="free"
          title="Free"
          price={planPriceLine(free)}
          features={FREE_FEATURES}
          isActive={active === 'free'}
        />
        <PlanCard
          planId="pro"
          title="Premium"
          price={planPriceLine(pro)}
          priceNote="Paid once by UPI, no auto-renew"
          features={PRO_FEATURES}
          isActive={active === 'pro'}
          highlighted
          onUpgrade={onUpgrade ? () => onUpgrade('pro') : undefined}
          upgrading={upgrading}
          ctaLabel={active === 'max' ? null : 'Get Premium'}
        />
        <PlanCard
          planId="max"
          title="Max"
          price={planPriceLine(max)}
          priceNote="Paid once by UPI, no auto-renew"
          features={MAX_FEATURES}
          isActive={active === 'max'}
          highlighted
          onUpgrade={onUpgrade ? () => onUpgrade('max') : undefined}
          upgrading={upgrading}
          ctaLabel={active === 'pro' ? 'Upgrade to Max' : 'Get Max'}
        />
      </div>

      {upgradeNotice && (
        <p className="text-xs text-muted-foreground text-center">{upgradeNotice}</p>
      )}
    </div>
  );
}

interface PlanCardProps {
  planId: PlanId;
  title: string;
  price: string;
  priceNote?: string;
  features: { label: string; included: boolean }[];
  isActive: boolean;
  highlighted?: boolean;
  onUpgrade?: () => void;
  upgrading?: boolean;
  /** Button text; null hides the button (e.g. Premium when already on Max). */
  ctaLabel?: string | null;
}

function PlanCard({
  title,
  price,
  priceNote,
  features,
  isActive,
  highlighted,
  onUpgrade,
  upgrading,
  ctaLabel = 'Get Premium',
}: PlanCardProps) {
  return (
    <Card
      className={cn(
        'p-6 flex flex-col',
        highlighted
          ? 'border-2 border-blue-300 dark:border-blue-800 bg-gradient-to-br from-blue-50/60 to-sky-50/60 dark:from-blue-950/20 dark:to-sky-950/20 shadow-soft'
          : 'border border-border'
      )}
    >
      <div className="flex items-center justify-between mb-4">
        <div className="flex items-center gap-2">
          <div
            className={cn(
              'w-9 h-9 rounded-lg flex items-center justify-center',
              highlighted ? 'gradient-blue' : 'bg-slate-100 dark:bg-slate-800'
            )}
          >
            {highlighted ? (
              <Crown className="w-5 h-5 text-white" />
            ) : (
              <Sparkles className="w-5 h-5 text-slate-500" />
            )}
          </div>
          <h2 className="text-lg font-semibold">{title}</h2>
        </div>
        {isActive && (
          <span className="text-[11px] font-medium px-2.5 py-1 rounded-full bg-green-100 dark:bg-green-950/40 text-green-700 dark:text-green-400 border border-green-200 dark:border-green-900">
            Current plan
          </span>
        )}
      </div>

      <div className="mb-5">
        <p className="text-4xl font-bold tracking-tight">{price}</p>
        {priceNote && <p className="text-xs text-muted-foreground mt-1">{priceNote}</p>}
      </div>

      <div className="space-y-2.5 flex-1">
        {features.map((f, i) => (
          <div key={i} className="flex items-start gap-2 text-sm">
            {f.included ? (
              <Check className="w-4 h-4 text-green-600 flex-shrink-0 mt-0.5" />
            ) : (
              <X className="w-4 h-4 text-slate-400 flex-shrink-0 mt-0.5" />
            )}
            <span className={f.included ? '' : 'text-muted-foreground'}>{f.label}</span>
          </div>
        ))}
      </div>

      {highlighted && (
        <div className="mt-6">
          {isActive ? (
            <Button className="w-full" disabled>
              <Check className="w-4 h-4 mr-2" /> Your current plan
            </Button>
          ) : ctaLabel === null ? null : (
            <>
              <Button className="w-full" onClick={onUpgrade} disabled={upgrading || !onUpgrade}>
                {upgrading ? (
                  <Loader2 className="w-4 h-4 mr-2 animate-spin" />
                ) : (
                  <Sparkles className="w-4 h-4 mr-2" />
                )}
                {ctaLabel}
              </Button>
              <p className="text-[11px] text-muted-foreground text-center mt-2">
                Pay by UPI and we&rsquo;ll switch {title} on, usually within a few hours.
              </p>
            </>
          )}
        </div>
      )}
    </Card>
  );
}
